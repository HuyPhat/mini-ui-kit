import StyleDictionary from 'style-dictionary';

// One build per theme: SD cannot hold the same token name (e.g. color.bg) in
// several themes at once. Primitives are only `include`d so aliases resolve
// to var(--gray-900) etc. without being emitted again.
const primitives = ['tokens/primitives.json'];
const themes = [
  {
    name: 'light',
    selector: ':root',
    source: [...primitives, 'tokens/global.json', 'tokens/semantic.light.json'],
    include: [],
  },
  { name: 'dark', selector: "[data-theme='dark']", source: ['tokens/semantic.dark.json'], include: primitives },
  { name: 'brand', selector: "[data-theme='brand']", source: ['tokens/semantic.brand.json'], include: primitives },
];

for (const { name, selector, source, include } of themes) {
  const sd = new StyleDictionary({
    usesDtcg: true,
    source,
    include,
    log: { verbosity: 'silent' },
    platforms: {
      css: {
        transformGroup: 'css',
        buildPath: 'src/tokens/generated/',
        files: [
          {
            destination: `${name}.css`,
            format: 'css/variables',
            filter: (token) => token.isSource,
            options: { selector, outputReferences: true, fileHeader: () => ['Generated by scripts/build-tokens.mjs. Do not edit.'] },
          },
        ],
      },
    },
  });
  await sd.buildAllPlatforms();
}
